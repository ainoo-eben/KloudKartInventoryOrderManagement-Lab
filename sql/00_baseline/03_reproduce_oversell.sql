-- Set up an isolated, deliberately unsafe one-unit race fixture.
-- Run scripts/run_baseline_race.ps1 to execute two concurrent attempts and
-- remove this temporary schema afterwards. Never use this function for orders.

\set ON_ERROR_STOP on

BEGIN;

DO $$
BEGIN
    IF to_regnamespace('kloudkart_baseline_race') IS NOT NULL THEN
        RAISE EXCEPTION
            'Schema kloudkart_baseline_race already exists; inspect it before cleanup or choose another name.';
    END IF;
END
$$;

CREATE SCHEMA kloudkart_baseline_race;

CREATE TABLE kloudkart_baseline_race.stock_fixture (
    product_id integer PRIMARY KEY,
    stock_quantity integer NOT NULL
);

CREATE TABLE kloudkart_baseline_race.attempts (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    observed_stock integer NOT NULL,
    outcome text NOT NULL
);

INSERT INTO kloudkart_baseline_race.stock_fixture (product_id, stock_quantity)
VALUES (1, 1);

CREATE FUNCTION kloudkart_baseline_race.try_order(p_product_id integer)
RETURNS text
LANGUAGE plpgsql
AS $function$
DECLARE
    observed_stock integer;
BEGIN
    SELECT stock_quantity
    INTO observed_stock
    FROM kloudkart_baseline_race.stock_fixture
    WHERE product_id = p_product_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Race fixture product % was not found', p_product_id;
    END IF;

    IF observed_stock < 1 THEN
        INSERT INTO kloudkart_baseline_race.attempts
            (product_id, observed_stock, outcome)
        VALUES (p_product_id, observed_stock, 'out of stock');
        RETURN 'out of stock';
    END IF;

    -- Give the second session time to read the same last unit.
    PERFORM pg_sleep(5);

    -- This decrement is not protected by the earlier stock check.
    UPDATE kloudkart_baseline_race.stock_fixture
    SET stock_quantity = stock_quantity - 1
    WHERE product_id = p_product_id;

    INSERT INTO kloudkart_baseline_race.attempts
        (product_id, observed_stock, outcome)
    VALUES (p_product_id, observed_stock, 'success');

    RETURN 'success';
END
$function$;

COMMIT;
